BEGIN;
-- Recipe Manager Database Schema
-- Database: recipe_manager

-- Drop tables if they exist (for fresh setup)



-- Users Table
CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Recipes Table
CREATE TABLE IF NOT EXISTS recipes (
    recipe_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,
    title VARCHAR(100) NOT NULL,
    description TEXT,
    ingredients TEXT NOT NULL,
    instructions TEXT NOT NULL,
    cooking_time INT,
    category VARCHAR(50),
    image_url VARCHAR(255),
    is_favorite BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
);

-- Create indexes for better performance
CREATE INDEX IF NOT EXISTS idx_user_id ON recipes(user_id);
CREATE INDEX IF NOT EXISTS idx_category ON recipes(category);
CREATE INDEX IF NOT EXISTS idx_is_favorite ON recipes(is_favorite);


CREATE OR REPLACE FUNCTION touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at = CURRENT_TIMESTAMP; RETURN NEW; END $$;
DROP TRIGGER IF EXISTS touch_updated_at ON recipes;
CREATE TRIGGER touch_updated_at BEFORE UPDATE ON recipes FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

COMMIT;
